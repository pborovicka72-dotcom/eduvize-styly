import assert from 'node:assert/strict';
import fs from 'node:fs';
import zlib from 'node:zlib';
import vm from 'node:vm';
const base=new URL('./',import.meta.url),scope={};
vm.runInNewContext(fs.readFileSync(new URL('school-card.js',base),'utf8'),scope);
vm.runInNewContext(fs.readFileSync(new URL('engine.js',base),'utf8'),scope);
const data=JSON.parse(zlib.gunzipSync(fs.readFileSync(new URL('schools.json.gz',base))));
const items=data.items.map(row=>Object.fromEntries(data.fields.map((key,i)=>[key,row[i]||''])));
const api=scope.EduvizeSchoolCard;
const schools=api.schoolsOnly(items);
assert.equal(schools.length,new Set(schools.map(s=>s.red_izo)).size);
assert.ok(schools.every(s=>s.school_type!=='OTHER'));
const found=api.search(schools,'pod zvahovem').find(x=>x.school_type==='ZS');
assert.ok(found);assert.equal(found.ico,'06919448');assert.equal(found.district,'Praha 5');
assert.equal(api.search(schools,found.izo).length,0);
assert.ok(api.search(schools,found.red_izo).some(x=>x.izo===found.izo));
assert.equal(api.search(items,'nenalezitelna skola 999999999999').length,0);
assert.equal(api.calendarDistrict('Praha 5'),'Praha 1 až 5');
assert.equal(api.calendarDistrict('Praha 9'),'Praha 6 až 10');
const events=JSON.parse(fs.readFileSync(new URL('events.json',base)));
assert.ok(scope.EduvizeCalendar.select(events,{...found,calendar_district:api.calendarDistrict(found.district)}).some(x=>x.id.startsWith('spring-')));
const html=fs.readFileSync(new URL('../../ucet.html',base),'utf8');
assert.ok(!/href="index.html"|id="lat"|id="lon"|<select id="district"/.test(html));
assert.ok(!html.includes('Správa aplikací →'));assert.ok(html.includes('admin-components.css'));
for(const [n,text] of [[0,'Nalezeno 0 škol'],[1,'Nalezena 1 škola'],[2,'Nalezeny 2 školy'],[4,'Nalezeny 4 školy'],[5,'Nalezeno 5 škol'],[21,'Nalezeno 21 škol']])assert.equal(api.countSchools(n),text);
console.log('School search, identifiers, district, calendar compatibility and central layout checks passed.');
